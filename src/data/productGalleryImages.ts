/**
 * Get all gallery images for a product based on its ID and sport.
 * Returns all views (front, back, kit, socks, etc.) for the matching style.
 */
export function getProductGalleryImages(productId: string, sport: string): GalleryImage[] {
  const styleNumber = extractStyleNumber(productId);
  if (!styleNumber) return [];
  
  const sportGallery = sportGalleries[sport];
  if (!sportGallery) return [];
  
  return sportGallery[styleNumber] || [];
}
